#!/usr/bin/env node
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { loadAPLCatalog } from "../../../src/aoe/catalog/index.js";

const OUT = "supabase/functions/aoe/generated/apl-catalog.generated.ts";
const REPORT_DIR = "reports/aoe/infrastructure-activation";

function sha256(value) {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function pruneModel(model) {
  return {
    modelCode: model.modelCode,
    modelVersion: model.modelVersion,
    aplRelease: model.aplRelease,
    split: model.split,
    strategy: model.strategy,
    experienceLevel: model.experienceLevel,
    frequency: model.frequency,
    minimumSessionDuration: model.minimumSessionDuration,
    maximumSessionDuration: model.maximumSessionDuration,
    equipmentProfile: model.equipmentProfile,
    specializationTarget: model.specializationTarget ?? null,
    checksum: model.checksum,
    metadata: model.metadata ?? {},
  };
}

export function buildRuntimeCatalog() {
  const loaded = loadAPLCatalog({ activeReleases: ["SPRINT_01", "SPRINT_02"], cache: false });
  if (loaded.errors.length > 0 || loaded.statistics.modelsValid !== 30 || loaded.statistics.checksumsValid !== 30) {
    throw new Error("APL catalog is not valid for runtime bundle.");
  }
  const models = loaded.catalog.map(pruneModel).sort((a, b) => a.modelCode.localeCompare(b.modelCode));
  const payload = {
    generatedAt: "2026-07-15T00:00:00.000Z",
    catalogAdapterVersion: loaded.versions.catalogAdapter,
    releases: loaded.releases.map((release) => ({
      releaseId: release.releaseId,
      releaseVersion: release.releaseVersion,
      status: release.status,
      frozenAt: release.frozenAt,
      modelCount: release.modelCount,
    })),
    statistics: loaded.statistics,
    models,
  };
  const checksum = sha256(JSON.stringify(payload));
  const source = `// Generated by npm run aoe:infra:build-catalog. Do not edit manually.\nexport const AOE_RUNTIME_CATALOG = ${JSON.stringify({ ...payload, aggregateChecksum: checksum }, null, 2)};\n`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, source);
  fs.mkdirSync(REPORT_DIR, { recursive: true });
  const report = { status: "PASS", output: OUT, models: models.length, releases: payload.releases.length, checksumsValid: loaded.statistics.checksumsValid, aggregateChecksum: checksum };
  fs.writeFileSync(path.join(REPORT_DIR, "catalog-bundle-report.json"), `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(path.join(REPORT_DIR, "catalog-bundle-report.md"), `# Catalog Bundle Report\n\n- Status: PASS\n- Output: ${OUT}\n- Models: ${models.length}\n- Releases: ${payload.releases.length}\n- Checksums valid: ${loaded.statistics.checksumsValid}\n- Aggregate checksum: ${checksum}\n`);
  return report;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  try {
    const result = buildRuntimeCatalog();
    process.stdout.write(`AOE runtime catalog built: ${result.models} models\n`);
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}
